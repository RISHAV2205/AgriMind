"""Generate explainable next steps without inventing fertilizer doses or profit."""

from typing import Any


FOLIAR_DISEASES = {
    "tomato_early_blight",
    "tomato_late_blight",
    "tomato_leaf_mold",
    "tomato_septoria_leaf_spot",
}


class RecommendationAgent:
    """Rule-based first recommendation layer for the current tomato classifier."""

    name = "recommendation_agent"

    def recommend(
        self,
        *,
        crop: str,
        disease: dict[str, Any] | None,
        field_data: dict[str, Any] | None,
    ) -> dict[str, Any]:
        recommendations: list[dict[str, str]] = []
        warnings: list[str] = []

        if disease:
            disease_name = str(disease.get("name", "")).lower()
            confidence = float(disease.get("confidence", 0.0))
            if confidence < 0.70:
                recommendations.append(self._item(
                    "high", "crop_health", "Confirm the diagnosis",
                    "Take clear photos of several affected leaves and ask a local extension officer or agronomist to confirm before treating the crop.",
                    "The image classifier confidence is below 70%, so a disease-specific action could be wrong.",
                    "Disease model confidence",
                ))
            elif disease_name.endswith("healthy"):
                recommendations.append(self._item(
                    "medium", "crop_health", "Keep scouting the crop",
                    "Check the undersides of leaves and nearby plants regularly, and upload a new image if symptoms appear.",
                    "The image model classified this image as healthy; continue monitoring because one image cannot rule out field-wide problems.",
                    "Disease model classification",
                ))
            elif disease_name in FOLIAR_DISEASES:
                recommendations.append(self._item(
                    "high", "crop_health", "Reduce spread while confirming the result",
                    "Inspect nearby plants, avoid wetting foliage during irrigation, remove badly affected leaves when practical, and clean tools after handling them. Dispose of infected plant material away from the crop. Get local confirmation before applying a plant-protection product.",
                    "The model detected a likely foliar disease. These hygiene and moisture-management steps are general precautions, not a confirmed diagnosis or pesticide prescription.",
                    "Disease model classification; confirm with a local agronomist",
                ))
            else:
                recommendations.append(self._item(
                    "high", "crop_health", "Get the crop checked",
                    "Have an agronomist inspect the crop before selecting a treatment.",
                    "The model result is not mapped to a reviewed crop-specific action in this version.",
                    "Disease model classification",
                ))

        # Current field values are generated by the simulator, not a calibrated lab test.
        source = str((field_data or {}).get("source", "")).lower()
        if source == "simulator":
            reason = "The available soil values are simulated and cannot establish nutrient deficiency."
        elif field_data:
            reason = "Sensor readings alone do not provide a calibrated soil-test fertilizer prescription."
        else:
            reason = "No verified soil test result is available for this field."
        recommendations.append(self._item(
            "medium", "fertilizer", "Base fertilizer on a soil test",
            f"For {crop}, collect a representative soil sample and request a crop- and region-specific recommendation. Share the test results and crop growth stage to get a more specific plan. Do not apply extra fertilizer based on the dashboard's simulated values.",
            reason,
            "Soil-test based nutrient management guidance (ICAR)",
        ))

        recommendations.append(self._item(
            "medium", "profitability", "Protect yield and avoid unnecessary input costs",
            "Scout regularly, act on confirmed problems early, and keep a record of fertilizer, crop-protection, labor, and harvest costs. Use only locally approved products at label directions after diagnosis.",
            "Preventing avoidable crop loss and input waste supports margins. This version has no local produce prices or farm cost history, so it cannot calculate or promise profit changes.",
            "General integrated crop management; farm-specific economics not connected",
        ))

        return {"data": recommendations, "warnings": warnings}

    @staticmethod
    def _item(priority: str, category: str, title: str, action: str, reason: str, basis: str) -> dict[str, str]:
        return {
            "priority": priority,
            "category": category,
            "title": title,
            "action": action,
            "reason": reason,
            "basis": basis,
        }
